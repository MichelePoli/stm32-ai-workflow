def get_ioc_template(board_name: str) -> str:
    """Restituisce il template IOC in base al nome board parziale"""
    b = board_name.upper()
    if "H743" in b or "H7" in b:
        return IOC_H743ZI
    elif "F401" in b or "F4" in b:
        return IOC_F401
    else:
        # Default fallback to F401 if unknown
        return IOC_F401
